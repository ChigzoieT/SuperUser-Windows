double adjust_speed(double inputSpeed) {
    double best = allowedSpeeds[0];
    double minDiff = fabs(inputSpeed - allowedSpeeds[0]);
    for (int i = 1; i < NUM_SPEEDS; i++) {
        double diff = fabs(inputSpeed - allowedSpeeds[i]);
        if (diff < minDiff) {
            minDiff = diff;
            best = allowedSpeeds[i];
        }
    }
    return best;
}

int get_thread_count(int cores, double speed) {
    if (cores < 1 || cores > NUM_CORES) {
        return -1;
    }
    
    // Find the column index corresponding to the (adjusted) speed.
    int colIndex = -1;
    for (int i = 0; i < NUM_SPEEDS; i++) {
        if (fabs(speed - allowedSpeeds[i]) < 0.001) {
            colIndex = i;
            break;
        }
    }
    if (colIndex == -1) {
        return -1;
    }
    
    return threadTable[cores - 1][colIndex];
}
